// Scans the app for every kebab-case icon name referenced by <dy-icon> (in
// templates and TS literals), intersects with the real lucide icon set, and
// emits src/app/lucide-icons.ts — a tree-shaken map so the bundle ships only the
// icons we actually use (instead of the full ~400KB vendored UMD), and the icon
// component can render each glyph directly without a whole-document re-scan.
//
//   node tools/gen-lucide-subset.mjs
//
// Over-inclusion is harmless (a stray kebab string that happens to be a real
// icon just bundles one extra glyph); omission would break an icon, so we err
// toward inclusion. Re-run after adding new icons.
import * as lucide from 'lucide';
import { readFile, writeFile, readdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join, extname } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = join(root, 'src', 'app');

async function walk(dir) {
  const out = [];
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) out.push(...(await walk(p)));
    else if (['.html', '.ts'].includes(extname(e.name)) && !e.name.endsWith('.spec.ts')) out.push(p);
  }
  return out;
}

const toPascal = (kebab) =>
  kebab.split('-').map((s) => (s ? s[0].toUpperCase() + s.slice(1) : '')).join('');

async function main() {
  const files = await walk(srcDir);
  const candidates = new Set();
  for (const f of files) {
    const text = await readFile(f, 'utf8');
    // Any quoted all-lowercase token (single word OR kebab) is a candidate; the
    // lucide-export check below keeps only real icon names, so over-matching
    // (CSS classes, restart policies, etc.) is harmless — but MISSING a token is
    // not, so we cast wide and let the intersection filter.
    for (const m of text.matchAll(/['"]([a-z][a-z0-9]*(?:-[a-z0-9]+)*)['"]/g)) candidates.add(m[1]);
  }

  const map = {};
  const droppedIconish = [];
  for (const name of candidates) {
    const pascal = toPascal(name);
    if (lucide[pascal] && Array.isArray(lucide[pascal])) map[name] = pascal;
    else if (name.includes('-')) droppedIconish.push(`${name} (${pascal})`); // likely-icon kebab that isn't valid → surface typos
  }

  const names = Object.keys(map).sort();
  const imports = [...new Set(names.map((n) => map[n]))].sort();

  const out = `// AUTO-GENERATED by tools/gen-lucide-subset.mjs — do not edit by hand.
// Regenerate after adding/removing <dy-icon> usages:  node tools/gen-lucide-subset.mjs
import {
  ${imports.join(',\n  ')},
  type IconNode,
} from 'lucide';

/** Kebab icon name -> lucide IconNode, tree-shaken to only the icons in use. */
export const ICONS: Record<string, IconNode> = {
${names.map((n) => `  '${n}': ${map[n]},`).join('\n')}
};
`;

  await writeFile(join(srcDir, 'lucide-icons.ts'), out);
  console.log(`lucide-icons.ts: ${names.length} icons (${imports.length} unique imports)`);
  if (droppedIconish.length) {
    console.log(`note: ${droppedIconish.length} kebab token(s) looked icon-ish but are not valid lucide names (ignored):`);
    console.log('  ' + droppedIconish.sort().join(', '));
  }
}

main().catch((e) => { console.error(e); process.exit(1); });
